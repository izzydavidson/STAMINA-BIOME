#!/usr/bin/env bash
# databases/rebuild_site_db.sh
#
# Incrementally add genomes to one custom site DB and rebuild its Kraken2 +
# Bracken indexes WITHOUT disturbing the curated parts of the existing build
# (hand-curated seqid2taxid.map, removed contaminants).
# Plan and rationale: databases/REBUILD_PLAN_2026-11.md
#
# Usage:
#   bash databases/rebuild_site_db.sh <gut|oral|skin> <phase> [<phase> ...]
#   bash databases/rebuild_site_db.sh <gut|oral|skin> all
#
# Phases (`all` = preflight .. record; record only runs if compare passes):
#   preflight  check Docker, image, drive, inputs, free space
#   baseline   classify validation inputs with the CURRENT DB
#   stage      move unregistered orphans out of library/added, download the rest,
#              validate headers / taxids / sizes
#   backup     copy current index + Bracken files to the work dir
#   add        kraken2-build --add-to-library each staged genome and append its
#              seqids to the existing (curated) seqid2taxid.map
#   build      remove old hash/opts/taxo + database.kraken + Bracken files,
#              run kraken2-build --build
#   bracken    bracken-build for read lengths 150 and 1500
#   verify     content checks (fresh files, seqid map, minimizers, kmer_distrib,
#              no unexpected taxa)
#   after      classify the same validation inputs with the NEW DB
#   compare    before/after report; exits non-zero if acceptance criteria fail
#   record     append any rows missing from databases/<site>/genome_list.tsv
#   rollback   restore the backup and remove the newly added library files
#
# Env overrides: CUSTOM_DB_BASE, WORK_BASE, THREADS, IMAGE, CAMISIM_FQ
# Do not edit this file while it is running (bash reads scripts incrementally).

set -euo pipefail

SITE="${1:-}"; shift || true
REPO="$(cd "$(dirname "$0")/.." && pwd)"
CUSTOM_DB_BASE="${CUSTOM_DB_BASE:-/Volumes/MyPassport/custom_db}"
WORK_BASE="${WORK_BASE:-${CUSTOM_DB_BASE}/_rebuild_2026-11}"
THREADS="${THREADS:-6}"
IMAGE="${IMAGE:-stamina-biome-tools-lr:dev}"
READLENS="150 1500"
KMER=35
BRACKEN_READLEN=1500
FP_MAX=0.001          # an added taxon above 0.1 % of a CAMISIM mock = false positive
BC_MAX=0.05           # max Bray-Curtis shift on the mock (before vs after)

TEST6_DIR="${HOME}/Desktop/test_femhs_471_test6/lr_meta/results/nonhuman/20261105_091056"
TEST6_PREFIX="4c927e32-418c-4a71-bc8b-7066dca63db7_EXP-PBC001_"
CAM="${HOME}/camisim_output"

# Validated per-site Kraken2 parameters (databases/README.md) + validation inputs
case "$SITE" in
  gut)  CONF=0.03; MHG=4
        CAMISIM_FQ="${CAMISIM_FQ:-${CAM}/mock_metagenome_gut/nanopore_work/9f/42539c12f87cf1a57f20c7225ccc3a/sample_0.fq.gz}"
        TEST6="Gut_Low:06 Gut_Med:07 Gut_High:08" ;;
  oral) CONF=0.04; MHG=4
        CAMISIM_FQ="${CAMISIM_FQ:-${CAM}/mock_metagenome_oral/nanopore/sample_0/reads/fastq/sample_0.fq.gz}"
        TEST6="Oral_Low:03 Oral_Med:04 Oral_High:05" ;;
  skin) CONF=0.03; MHG=4
        CAMISIM_FQ="${CAMISIM_FQ:-${CAM}/mock_metagenome_skin/nanopore/sample_0/reads/fastq/sample_0.fq.gz}"
        TEST6="Skin_Low:01 Skin_Med:02" ;;
  *) sed -n 2,32p "$0"; echo; echo "First argument must be gut, oral or skin (vaginal is already complete)."; exit 1 ;;
esac

DB="${CUSTOM_DB_BASE}/${SITE}"
WORK="${WORK_BASE}/${SITE}"
ADDITIONS="${REPO}/databases/${SITE}/additions_2026-11.tsv"
GENOME_LIST="${REPO}/databases/${SITE}/genome_list.tsv"
STAGE="${WORK}/staging"
BACKUP="${WORK}/backup"
ADDED_LOG="${WORK}/added_library_files.tsv"
LOG="${WORK}/rebuild.log"

inputs() {
  echo "camisim_${SITE}|${CAMISIM_FQ}"
  local pair
  for pair in $TEST6; do echo "${pair%%:*}|${TEST6_DIR}/${TEST6_PREFIX}barcode${pair##*:}/nonhuman.fastq.gz"; done
}
additions() { grep -v '^#' "$ADDITIONS" | awk -F'\t' '$1!="accession" && $1!="" {print $1"\t"$2"\t"$3}'; }

log() { local m="[$(date '+%Y-%m-%d %H:%M:%S')] [$SITE] $*"; echo "$m"; [[ -d "$WORK" ]] && echo "$m" >> "$LOG"; return 0; }
die() { log "[FATAL] $*"; exit 1; }
dk()  { docker run --rm -v "${DB}:/db:rw" "$IMAGE" "$@"; }

# ─────────────────────────────────────────────────────────────────────────────
phase_preflight() {
  docker info >/dev/null 2>&1 || die "Docker is not running"
  docker run --rm "$IMAGE" true >/dev/null 2>&1 || die "Image not runnable: $IMAGE"
  [[ -d "$DB/library/added" && -f "$DB/hash.k2d" ]] || die "DB not found/incomplete: $DB (is MyPassport mounted?)"
  [[ -f "$ADDITIONS" ]] || die "Missing $ADDITIONS"
  local free_gb; free_gb=$(df -g "$DB" | awk 'NR==2{print $4}')
  (( free_gb >= 20 )) || die "Only ${free_gb} GB free on the DB drive; need >= 20 GB"
  inputs | while IFS='|' read -r lab p; do [[ -s "$p" ]] || die "Validation input missing ($lab): $p"; done
  mkdir -p "$WORK" "$STAGE" "$BACKUP"
  log "Preflight OK — DB=$DB conf=$CONF mhg=$MHG free=${free_gb}GB threads=$THREADS additions=$(additions | wc -l | tr -d ' ')"
}

# ─────────────────────────────────────────────────────────────────────────────
classify_all() {  # $1 = baseline|after
  local out="${WORK}/$1"; mkdir -p "$out"
  inputs | while IFS='|' read -r lab p; do
    local d="${out}/${lab}"; mkdir -p "$d"
    log "[$1] kraken2 $lab"
    docker run --rm -v "${DB}:/db:ro" -v "$(dirname "$p"):/in:ro" -v "${d}:/out:rw" "$IMAGE" \
      kraken2 --db /db --threads "$THREADS" --memory-mapping \
        --confidence "$CONF" --minimum-hit-groups "$MHG" \
        --report "/out/${lab}.kreport" --output /dev/null "/in/$(basename "$p")" 2>> "$LOG"
    docker run --rm -v "${DB}:/db:ro" -v "${d}:/out:rw" "$IMAGE" \
      bracken -d /db -i "/out/${lab}.kreport" -o "/out/${lab}.bracken" -w "/out/${lab}.breport" \
        -r "$BRACKEN_READLEN" -l S >> "$LOG" 2>&1 || log "  [WARN] bracken failed for $lab"
  done
}
phase_baseline() {
  [[ -f "${WORK}/build_started" ]] && die "Build already started — baseline must come from the original DB"
  classify_all baseline
}
phase_after() { classify_all after; }

# ─────────────────────────────────────────────────────────────────────────────
phase_stage() {
  mkdir -p "$STAGE"
  local moved=0
  while IFS=$'\t' read -r acc taxid sp; do
    local orphan
    orphan=$(ls "$DB/library/added/" | grep -E "^${taxid}_${acc}_.*genomic\.fna$" || true)
    if [[ -n "$orphan" ]]; then mv "$DB/library/added/$orphan" "$STAGE/"; moved=$((moved+1)); fi
  done < <(additions)
  log "Moved $moved unregistered orphan file(s) from library/added to staging"
  python3 -I - "$REPO/databases" "$STAGE" "$ADDITIONS" <<'PY'
import sys, time
sys.path.insert(0, sys.argv[1])
import expand_all_sites as e
from pathlib import Path
stage = Path(sys.argv[2])
for line in open(sys.argv[3]):
    if line.startswith("#") or line.startswith("accession") or not line.strip():
        continue
    acc, taxid, sp = line.rstrip("\n").split("\t")[:3]
    if list(stage.glob(f"{taxid}_{acc}_*genomic.fna")):
        continue
    print(f"  downloading {sp} ({acc})")
    ftp = e.resolve_ftp_path(acc); time.sleep(e.API_SLEEP)
    if not ftp:
        sys.exit(f"  [FAIL] could not resolve FTP for {acc}")
    if not e.download_genome(int(taxid), sp, ftp, stage):
        sys.exit(f"  [FAIL] download failed for {acc}")
PY
  local n=0
  while IFS=$'\t' read -r acc taxid sp; do
    local f; f=$(ls "$STAGE"/${taxid}_${acc}_*genomic.fna 2>/dev/null | head -1)
    [[ -s "$f" ]] || die "Staged file missing for $acc ($sp)"
    local bad bp
    bad=$(grep '^>' "$f" | grep -vc "^>kraken:taxid|${taxid}|" || true)
    [[ "$bad" == "0" ]] || die "$acc: $bad headers lack kraken:taxid|$taxid|"
    awk -F'\t' -v t="$taxid" '$1==t {found=1; exit} END {exit !found}' "$DB/taxonomy/nodes.dmp" \
      || die "taxid $taxid ($sp) not in $DB/taxonomy/nodes.dmp"
    bp=$(grep -v '^>' "$f" | tr -d '\n' | wc -c | tr -d ' ')
    (( bp > 500000 )) || die "$acc: only $bp bp — not a full genome"
    n=$((n+1))
  done < <(additions)
  log "Staged and validated $n genome(s)"
}

# ─────────────────────────────────────────────────────────────────────────────
phase_backup() {
  mkdir -p "$BACKUP"
  if [[ -f "$BACKUP/hash.k2d" ]]; then log "Backup already present — not overwriting"; return 0; fi
  local f
  for f in hash.k2d opts.k2d taxo.k2d seqid2taxid.map database.kraken \
           database150mers.kraken database150mers.kmer_distrib \
           database1500mers.kraken database1500mers.kmer_distrib; do
    if [[ -f "$DB/$f" ]]; then cp -p "$DB/$f" "$BACKUP/"; fi
  done
  cp -p "$DB/library/added/prelim_map.txt" "$BACKUP/library_added_prelim_map.txt"
  log "Backup complete: $(du -sh "$BACKUP" | cut -f1)"
}

# ─────────────────────────────────────────────────────────────────────────────
phase_add() {
  [[ -f "$BACKUP/seqid2taxid.map" ]] || die "Run backup first"
  touch "$ADDED_LOG"
  while IFS=$'\t' read -r acc taxid sp; do
    if grep -q "^${acc}"$'\t' "$ADDED_LOG"; then continue; fi
    local f before after newmap newfna n
    f=$(basename "$(ls "$STAGE"/${taxid}_${acc}_*genomic.fna | head -1)")
    before=$(ls "$DB/library/added/" | sort)
    docker run --rm -v "${DB}:/db:rw" -v "${STAGE}:/stage:ro" "$IMAGE" \
      kraken2-build --add-to-library "/stage/$f" --db /db >> "$LOG" 2>&1
    after=$(ls "$DB/library/added/" | sort)
    newmap=$(comm -13 <(echo "$before") <(echo "$after") | grep '^prelim_map_.*\.txt$' || true)
    newfna=$(comm -13 <(echo "$before") <(echo "$after") | grep '\.fna$' || true)
    [[ -n "$newmap" && -n "$newfna" ]] || die "add-to-library produced no new files for $acc"
    n=$(grep -c "^TAXID" "$DB/library/added/$newmap")
    [[ "$n" == "$(grep -c '^>' "$STAGE/$f")" ]] || die "$acc: prelim map entry count != FASTA header count"
    # Append to the CURATED map rather than regenerating it.
    grep "^TAXID" "$DB/library/added/$newmap" | cut -f2- >> "$DB/seqid2taxid.map"
    printf '%s\t%s\t%s\t%s\t%s\n' "$acc" "$taxid" "$newfna" "$newmap" "$n" >> "$ADDED_LOG"
    log "  [ADDED] $sp ($n seqs)"
  done < <(additions)
  # The July maps already contain harmless repeats (same seqid, same taxid,
  # from genomes registered twice). Fail only on what this run could break:
  # a new seqid colliding with an existing one, or a seqid mapped to two taxids.
  local nnew collide conflict
  nnew=$(awk -F'\t' '{s+=$5} END {print s+0}' "$ADDED_LOG")
  collide=$(tail -n "$nnew" "$DB/seqid2taxid.map" | cut -f1 | sort -u \
            | comm -12 - <(cut -f1 "$BACKUP/seqid2taxid.map" | sort -u) | wc -l | tr -d ' ')
  conflict=$(sort -u "$DB/seqid2taxid.map" | cut -f1 | uniq -d | wc -l | tr -d ' ')
  [[ "$collide" == "0" ]] || die "$collide new seqid(s) already exist in the original map"
  # Same accession already indexed under a DIFFERENT taxid (e.g. a genus-level
  # or wrong-species label) makes Kraken push the whole genome to the LCA.
  local xlabel
  xlabel=$(sed -E 's/\|?kraken:taxid\|[0-9]+\|?//' "$DB/seqid2taxid.map" | sort -u | cut -f1 | uniq -d | head -20 | tr '\n' ' ')
  [[ -z "$xlabel" ]] || die "Accession(s) mapped to more than one taxid — fix the wrong label in seqid2taxid.map first: $xlabel"
  [[ "$conflict" == "0" ]] || die "$conflict seqid(s) map to more than one taxid"
  head -n "$(wc -l < "$BACKUP/seqid2taxid.map")" "$DB/seqid2taxid.map" | cmp -s - "$BACKUP/seqid2taxid.map" \
    || die "original seqid2taxid.map lines were modified"
  log "seqid2taxid.map: $(wc -l < "$BACKUP/seqid2taxid.map" | tr -d ' ') -> $(wc -l < "$DB/seqid2taxid.map" | tr -d ' ') lines"
}

# ─────────────────────────────────────────────────────────────────────────────
# The MyPassport drive is NTFS (Paragon UFSD); through Docker Desktop's mount
# its directories report nlink=0 and a recursive `find library/` returns
# nothing, while `find library/added/` works. Both kraken2-build and
# bracken-build discover genomes with the recursive form, so mount patched
# copies that search library/added/ directly. (All site libraries only have
# library/added/.)
PATCH_DIR=""
patched_tools() {
  PATCH_DIR="${WORK}/patched_tools"; mkdir -p "$PATCH_DIR"
  docker run --rm "$IMAGE" cat /usr/lib/kraken2/build_kraken2_db.sh > "$PATCH_DIR/build_kraken2_db.sh"
  docker run --rm "$IMAGE" cat /opt/bracken/bracken-build > "$PATCH_DIR/bracken-build"
  sed -i '' "s#find library/ '('#find library/added/ '('#" "$PATCH_DIR/build_kraken2_db.sh"
  sed -i '' 's#find -L $DATABASE/library \\(#find -L $DATABASE/library/added/ \\(#' "$PATCH_DIR/bracken-build"
  grep -q "find library/added/ '('" "$PATCH_DIR/build_kraken2_db.sh" || die "Could not patch build_kraken2_db.sh"
  grep -q 'find -L $DATABASE/library/added/ ' "$PATCH_DIR/bracken-build" || die "Could not patch bracken-build"
  chmod +x "$PATCH_DIR"/*
  local n
  n=$(docker run --rm -v "${DB}:/db:ro" "$IMAGE" sh -c "cd /db && find library/added/ -name '*.fna' | wc -l")
  (( n > 100 )) || die "Only $n .fna files visible in library/added/ inside the container"
  log "Patched tools ready; container sees $n library .fna files"
}

phase_build() {
  [[ -s "$ADDED_LOG" ]] || die "Nothing added yet (run add)"
  [[ -f "$BACKUP/hash.k2d" ]] || die "No backup — refusing to delete index"
  patched_tools
  touch "${WORK}/build_started"
  # kraken2-build skips steps whose output exists; bracken-build silently
  # reuses database.kraken. Remove all of them (they are in the backup).
  rm -f "$DB"/hash.k2d "$DB"/opts.k2d "$DB"/taxo.k2d "$DB"/database.kraken \
        "$DB"/database150mers.kraken "$DB"/database150mers.kmer_distrib \
        "$DB"/database1500mers.kraken "$DB"/database1500mers.kmer_distrib
  log "kraken2-build --build (threads=$THREADS)"
  docker run --rm -v "${DB}:/db:rw" -v "${PATCH_DIR}/build_kraken2_db.sh:/usr/lib/kraken2/build_kraken2_db.sh:ro" "$IMAGE" \
    kraken2-build --build --db /db --threads "$THREADS" 2>&1 | tee -a "$LOG"
  [[ -s "$DB/hash.k2d" ]] || die "hash.k2d not created"
  local nseq
  nseq=$(grep -o 'Completed processing of [0-9]* sequences' "$LOG" | tail -1 | grep -o '[0-9][0-9]*' | head -1)
  (( ${nseq:-0} > 0 )) || die "kraken2-build processed 0 sequences"
  check_minimizers
  log "Kraken2 index built: $(du -sh "$DB/hash.k2d" | cut -f1) from $nseq sequences"
}

# hash.k2d's file size is a pre-allocated capacity from a sampled estimate, so it
# can shrink slightly even when content grows. Compare stored minimizers instead.
table_size() {  # $1 = dir holding hash/opts/taxo.k2d
  docker run --rm -v "$1:/db:ro" "$IMAGE" kraken2-inspect --db /db --skip-counts 2>/dev/null \
    | awk -F': ' '/Table size/ {print $2+0}'
}
check_minimizers() {
  local old new
  old=$(table_size "$BACKUP"); new=$(table_size "$DB")
  (( ${new:-0} > 0 && ${old:-0} > 0 )) || die "Could not read minimizer counts (old=${old:-?} new=${new:-?})"
  (( new >= old )) || die "New index stores fewer minimizers ($new) than the original ($old)"
  log "Minimizers stored: $old -> $new"
}

phase_bracken() {
  [[ "$DB/hash.k2d" -nt "${WORK}/build_started" ]] || die "hash.k2d is not newer than build start"
  [[ -n "$PATCH_DIR" ]] || patched_tools
  rm -f "$DB/database.kraken" "$DB/database.kraken.tmp"
  local L
  for L in $READLENS; do
    log "bracken-build -l $L"
    docker run --rm -v "${DB}:/db:rw" -v "${PATCH_DIR}/bracken-build:/opt/bracken/bracken-build:ro" "$IMAGE" \
      /opt/bracken/bracken-build -d /db -t "$THREADS" -l "$L" -k "$KMER" 2>&1 | tee -a "$LOG"
    [[ "$DB/database${L}mers.kmer_distrib" -nt "${WORK}/build_started" ]] || die "database${L}mers.kmer_distrib was not regenerated"
  done
  # Expected count = original minus sequences of genomes that were moved out
  # of the library into staging but deliberately not added (excluded rows).
  local nk orig dropped=0 f acc
  nk=$(wc -l < "$DB/database.kraken" | tr -d ' ')
  orig=$(wc -l < "$BACKUP/database.kraken" | tr -d ' ')
  for f in "$STAGE"/*_genomic.fna; do
    [[ -e "$f" ]] || continue
    acc=$(basename "$f" | cut -d_ -f2,3)
    grep -q "^${acc}"$'\t' "$ADDED_LOG" || dropped=$((dropped + $(grep -c '^>' "$f")))
  done
  (( nk >= orig - dropped )) || die "database.kraken has $nk lines; expected >= $((orig - dropped)) (original $orig minus $dropped excluded)"
  log "Bracken built from $nk library sequences (original $orig, excluded $dropped)"
}

# ─────────────────────────────────────────────────────────────────────────────
phase_verify() {
  local fail=0 f okn=0
  for f in hash.k2d taxo.k2d opts.k2d database.kraken database150mers.kmer_distrib database1500mers.kmer_distrib; do
    [[ "$DB/$f" -nt "${WORK}/build_started" ]] || { log "  [FAIL] $f is stale or missing"; fail=1; }
  done
  log "kraken2-inspect (minimizer counts per taxon)…"
  dk kraken2-inspect --db /db > "${WORK}/inspect.txt" 2>> "$LOG"
  while IFS=$'\t' read -r acc taxid sp; do
    local nseq mini k150 k1500
    nseq=$(awk -F'\t' -v t="$taxid" '$2==t' "$DB/seqid2taxid.map" | wc -l | tr -d ' ')
    mini=$(awk -F'\t' -v t="$taxid" '$5==t {print $3+0; exit}' "${WORK}/inspect.txt")
    k150=$(awk -v t="$taxid" '{for(i=2;i<=NF;i++) if (index($i, t":")==1) {c++; break}} END {print c+0}' "$DB/database150mers.kmer_distrib")
    k1500=$(awk -v t="$taxid" '{for(i=2;i<=NF;i++) if (index($i, t":")==1) {c++; break}} END {print c+0}' "$DB/database1500mers.kmer_distrib")
    if [[ "$nseq" -gt 0 && "${mini:-0}" -gt 0 && "$k150" -gt 0 && "$k1500" -gt 0 ]]; then
      okn=$((okn+1))
    else
      log "  [FAIL] $sp ($taxid): seqs=$nseq direct_minimizers=${mini:-0} kmer150=$k150 kmer1500=$k1500"; fail=1
    fi
  done < <(additions)
  log "  $okn/$(additions | wc -l | tr -d ' ') additions present in map, index and both Bracken files"
  # No taxon may appear that was neither in the old map nor in the additions
  # (catches resurrected contaminants or stray library files).
  local unexpected
  unexpected=$(comm -13 <( { cut -f2 "$BACKUP/seqid2taxid.map"; additions | cut -f2; } | sort -u) \
                        <(cut -f2 "$DB/seqid2taxid.map" | sort -u) | tr '\n' ' ')
  [[ -z "$unexpected" ]] || { log "  [FAIL] unexpected taxids in seqid2taxid.map: $unexpected"; fail=1; }
  (( fail == 0 )) || die "Verification failed — see $LOG (rollback available)"
  log "Verification passed"
}

# ─────────────────────────────────────────────────────────────────────────────
phase_compare() {
  python3 -I - "$WORK" "$ADDITIONS" "camisim_${SITE}" "$FP_MAX" "$BC_MAX" <<'PY' | tee "${WORK}/compare_report.txt"
import sys, csv, os
work, adds, mock, fp_max, bc_max = sys.argv[1], sys.argv[2], sys.argv[3], float(sys.argv[4]), float(sys.argv[5])
new = {}
for line in open(adds):
    if line.startswith(("#", "accession")) or not line.strip(): continue
    a, t, s = line.rstrip("\n").split("\t")[:3]; new[t] = s
def bracken(p):
    d = {}
    if os.path.exists(p):
        for r in csv.DictReader(open(p), delimiter="\t"):
            d[r["taxonomy_id"]] = (r["name"], int(r["new_est_reads"]))
    return d
def classified(k):
    u = c = 0
    for l in open(k):
        f = l.split("\t")
        if f[3] == "U": u = int(f[1])
        if f[3] == "R": c = int(f[1])
    return c, u
labels = sorted(os.listdir(f"{work}/after"), key=lambda x: (x != mock, x))
failures = []
for lab in labels:
    b = bracken(f"{work}/baseline/{lab}/{lab}.bracken"); a = bracken(f"{work}/after/{lab}/{lab}.bracken")
    if not a or not b:
        failures.append(f"{lab}: missing baseline/after results"); continue
    cb, ub = classified(f"{work}/baseline/{lab}/{lab}.kreport"); ca, ua = classified(f"{work}/after/{lab}/{lab}.kreport")
    tb = sum(v for _, v in b.values()) or 1; ta = sum(v for _, v in a.values()) or 1
    fb = {k: v / tb for k, (_, v) in b.items()}; fa = {k: v / ta for k, (_, v) in a.items()}
    bc = 1 - sum(min(fb.get(k, 0), fa.get(k, 0)) for k in set(fb) | set(fa))
    print(f"\n== {lab}{'  (CAMISIM mock — contains none of the additions)' if lab == mock else ''}")
    print(f"   classified: {100*cb/max(cb+ub,1):.1f}% -> {100*ca/max(ca+ua,1):.1f}%   species: {len(b)} -> {len(a)}   Bray-Curtis: {bc:.3f}")
    hits = sorted(((fa.get(t, 0), s, a[t][1]) for t, s in new.items() if t in a), reverse=True)
    for f, s, r in hits:
        flag = "  <-- FALSE POSITIVE" if lab == mock and f > fp_max else ""
        print(f"   + {s:38s} {r:7d} reads {100*f:6.2f}%{flag}")
        if flag: failures.append(f"{lab}: {s} at {100*f:.2f}%")
    lost = sorted(b[k][0] for k in b if k not in a and fb[k] > 0.001)
    if lost: print(f"   - no longer reported (>0.1% before): {', '.join(lost)}")
    drops = sorted(((fa.get(k, 0) - fb[k], b[k][0]) for k in b if fb[k] > 0.01), key=lambda x: x[0])[:5]
    print("   biggest drops: " + "; ".join(f"{n} {100*d:+.2f}pp" for d, n in drops))
    if lab == mock:
        if lost: failures.append(f"{lab}: mock species lost: {', '.join(lost)}")
        if bc > bc_max: failures.append(f"{lab}: mock profile shifted (Bray-Curtis {bc:.3f} > {bc_max})")
print("\nRESULT:", "PASS" if not failures else "FAIL")
for f in failures: print("  -", f)
sys.exit(1 if failures else 0)
PY
}

phase_record() {
  local added=0
  while IFS=$'\t' read -r acc taxid sp; do
    awk -F'\t' -v t="$taxid" '$3==t {f=1} END {exit !f}' "$GENOME_LIST" && continue
    if (( added == 0 )); then printf '\n# ── additions_2026-11.tsv (absent from DB vs core_nt comparison) ──────\n' >> "$GENOME_LIST"; fi
    printf '%s\t%s\t%s\tadditions_2026-11\t%s\n' "$acc" "$sp" "$taxid" "Absent from DB; detected by core_nt comparison" >> "$GENOME_LIST"
    added=$((added+1))
  done < <(additions)
  log "genome_list.tsv: $added new row(s) appended (orphans were already listed)"
  touch "${WORK}/completed"
}

# ─────────────────────────────────────────────────────────────────────────────
phase_rollback() {
  [[ -f "$BACKUP/hash.k2d" ]] || die "No backup to restore"
  local f
  for f in "$BACKUP"/*; do
    case "$(basename "$f")" in
      library_added_prelim_map.txt) cp -p "$f" "$DB/library/added/prelim_map.txt" ;;
      *) cp -p "$f" "$DB/" ;;
    esac
  done
  if [[ -f "$ADDED_LOG" ]]; then
    while IFS=$'\t' read -r acc taxid fna map n; do
      rm -f "$DB/library/added/$fna" "$DB/library/added/$map"
    done < "$ADDED_LOG"
    mv "$ADDED_LOG" "${ADDED_LOG}.rolled_back"
  fi
  rm -f "${WORK}/build_started" "${WORK}/completed"
  log "Rollback complete — index restored; staged genomes kept in $STAGE"
}

